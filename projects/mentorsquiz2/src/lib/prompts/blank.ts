export const getBlankPrompt = (text: string) => {
  // Check if text contains user-specified blanks
  const hasUserBlanks = text.includes('[') && text.includes(']');
  
  const promptText = hasUserBlanks 
    ? text.replace(/\[(.*?)\]/g, '_'.repeat(10)) // Replace bracketed text with underscores
    : text;

  return `당신은 영어 지문을 입력받아 빈칸 채우기 문제를 만드는 수능 영어 전문가입니다. 다음 규칙에 따라 문제를 만들어주세요:

주어진 영어 지문을 읽고 다음 단계에 따라 빈칸 채우기 문제를 만드세요:
${hasUserBlanks 
  ? '1. 대괄호로 표시된 부분을 빈칸으로 만듭니다.'
  : '1. 지문의 핵심 주제나 요지를 가장 잘 반영하는 한 단어 또는 두 단어를 선택하여 하나의 빈칸으로 만듭니다.'}
2. [OUTPUT] 섹션에 다음과 같은 순서로 작성합니다:
   - "다음 빈칸에 들어갈 말로 가장 적절한 것을 고르시오."
   - 한 줄 띄우기
   - 빈칸이 포함된 전체 지문 (빈칸은 밑줄로 표시)
3. 5개의 선택지를 반드시 영어로만 만듭니다:
   - 정답은 ${hasUserBlanks ? '대괄호 안에 있던 표현' : '원문에서 제거한 단어나 구절'}과 같은 의미의 다른 영어 표현으로 패러프레이즈하여 제시해야 합니다. 원문 표현을 그대로 사용하지 마세요.
   - 나머지 4개의 오답은 문맥상 그럴듯하지만 정답보다는 덜 적절한 영어 표현이어야 합니다.
   - 모든 선택지는 반드시 영어로 작성되어야 합니다.
   - 선택지들은 로마 숫자와 함께 나열합니다 (①, ②, ③, ④, ⑤).
4. [정답] 섹션에 정답 번호를 적습니다.
5. [해설] 섹션에는 다음 내용을 간단명료하게 작성합니다:
   - 지문의 핵심 주제와 논리적 흐름
   - 정답이 가장 적절한 이유
   - 원문의 빈칸 표현: "${hasUserBlanks ? '[대괄호 안에 있던 표현]' : '(원문: _____)'}"
   - 각 오답이 적절하지 않은 이유

모든 섹션을 연속해서 작성하고, 각 섹션 사이에 빈 줄을 넣지 않습니다.

위의 규칙에 따라 다음 지문에 대한 빈칸 문제를 생성해주세요:

${promptText}`;
};